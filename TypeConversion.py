#  Type conversion
a = 2
b = 4.25

sum = a + b # 2.0 + 4.25 => 6.25
print(sum)

#  Type casting
a = "2"
c = int(a)
b = 4.25

sum = c + b # 2.0 + 4.25 => 6.25
print(sum)


