# Arithmetic Operators (+, -, *, /, %, **)
a = 5
b = 2

print("Arithmetic Operators")
print("a + b = ", a + b)
print("a - b = ", a - b)
print("a * b = ", a * b)
print("a / b = ", a / b)
print("a % b = ", a % b) #remainder
print("a ** b = ", a ** b) #a^b

# Releation / Comparison Operators (==, !=, >, <, >=, <=)
print("Comparison Operators")
print("a==b = " , a==b)
print("a!=b = " , a!=b)
print("a>b = " , a>b)
print("a<b = " , a<b)
print("a<=b = " , a<=b)
print("a>=b = " , a>=b)

